def concept_terms_for(point: KnowledgePoint) -> list[str]:
    """返回该知识点命中的概念对应的常用查询词（用于关键词增强）。"""
    terms: list[str] = []
    for concept, refs in CONCEPT_MAP.items():
        for law, article in refs:
            if law in point.source and article in point.clause:
                terms.extend(CONCEPT_KEYWORDS.get(concept, ()))
    return terms


def enrich_keywords(points: list[KnowledgePoint]) -> list[KnowledgePoint]:
    """把概念常用查询词注入对应条文知识点的关键词（去重、过滤过短），返回原列表。"""
    for p in points:
        for t in concept_terms_for(p):
            if len(t) > 1 and t not in p.keywords:
                p.keywords.append(t)
    return points
